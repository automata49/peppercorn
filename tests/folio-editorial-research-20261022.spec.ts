import {test,expect} from '@playwright/test'
import {demoRows} from '../src/data/mock'
for(const width of [390,834,1440])test(`research composer creates and edits source-backed notes without ticker at ${width}px`,async({page})=>{
 await page.setViewportSize({width,height:1000})
 await page.addInitScript(()=>{
  sessionStorage.setItem('peppercorn-intro-seen','1')
  localStorage.setItem('peppercorn-research','[]')
 })
 await page.route('**/data/leaderboard.json*',r=>r.fulfill({status:404,body:''}))
 await page.route('**/functions/v1/leaderboard?*',r=>r.fulfill({json:{rows:demoRows}}))
 await page.goto('/peppercorn/')
 const bottom=page.locator('.mobile-bottom-nav').getByRole('button',{name:'발견',exact:true})
 if(await bottom.isVisible())await bottom.click()
 else await page.locator('.sidebar nav').getByRole('button',{name:'발견',exact:true}).click()
 await page.getByRole('tab',{name:'리서치 기록',exact:true}).click()
 const editor=page.getByRole('region',{name:'리서치 기록 작성'})
 await expect(editor.locator('.folio-editorial-heading h3')).toHaveText('리서치 기록')
 await editor.getByRole('button',{name:/새 기록/}).click()
 await editor.getByLabel('기록 제목').fill('AI 공급망 실적 확인')
 await editor.getByLabel('확인한 사실').fill('실적 공시에서 출하량을 확인한다.')
 await editor.getByLabel('나의 해석').fill('수익성의 지속성을 추가 검토한다.')
 await editor.getByLabel('원문 출처 URL').fill('https://example.com/source')
 await editor.getByLabel('원문 출처 URL').blur()
 await expect.poll(()=>page.evaluate(()=>{
  const records=JSON.parse(localStorage.getItem('peppercorn-research')||'[]')
  return records[0]?.fact
 })).toBe('실적 공시에서 출하량을 확인한다.')
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('peppercorn-research')||'[]')[0]?.source)).toBe('https://example.com/source')
 await editor.getByLabel('원문 출처 URL').fill('javascript:alert(1)')
 await editor.getByLabel('원문 출처 URL').blur()
 await expect(editor.getByRole('status')).toContainText('http 또는 https')
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('peppercorn-research')||'[]')[0]?.source)).toBe('https://example.com/source')
 await page.reload()
 const nav=page.locator('.mobile-bottom-nav').getByRole('button',{name:'발견',exact:true})
 if(await nav.isVisible())await nav.click();else await page.locator('.sidebar nav').getByRole('button',{name:'발견',exact:true}).click()
 await page.getByRole('tab',{name:'리서치 기록',exact:true}).click()
 await expect(page.getByRole('region',{name:'리서치 기록 작성'}).getByLabel('기록 제목')).toHaveValue('AI 공급망 실적 확인')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})
test('detail headings share Folio Insight hierarchy and Thesis stays editable',async({page})=>{
 await page.addInitScript(()=>sessionStorage.setItem('peppercorn-intro-seen','1'))
 await page.route('**/data/leaderboard.json*',r=>r.fulfill({status:404,body:''}))
 await page.route('**/functions/v1/leaderboard?*',r=>r.fulfill({json:{rows:demoRows}}))
 await page.goto('/peppercorn/')
 const bottom=page.locator('.mobile-bottom-nav').getByRole('button',{name:'발견',exact:true})
 if(await bottom.isVisible())await bottom.click();else await page.locator('.sidebar nav').getByRole('button',{name:'발견',exact:true}).click()
 await page.getByRole('tab',{name:'종목 검토'}).click()
 await page.locator('.analysis-finder .stock-compact-row, .analysis-finder .stock-trend-row').first().click()
 const detail=page.locator('.obra-detail')
 await expect(detail.locator('.folio-insight header h3')).toHaveText('핵심 요약')
 await expect(detail.locator('.folio-editorial-heading h3')).toContainText(['주도력 점검','동일 산업 비교'])
 const refFont=await detail.locator('.folio-insight header h3').evaluate(el=>getComputedStyle(el).fontSize)
 for(const title of await detail.locator('.folio-editorial-heading h3').all())expect(await title.evaluate(el=>getComputedStyle(el).fontSize)).toBe(refFont)
 await expect(detail.locator('.folio-insight>header')).toHaveCSS('border-bottom-width','0px')
 for(const block of await detail.locator('.analysis-secondary-body>.analysis-block').all())await expect(block).toHaveCSS('border-bottom-width','0px')
 await page.getByRole('tab',{name:'Analysis',exact:true}).click()
 await expect(detail.locator('.folio-editorial-heading h3')).toContainText('모멘텀 분석')
 await page.getByRole('tab',{name:'Financials',exact:true}).click()
 await expect(detail.locator('.folio-editorial-heading h3')).toContainText('공시 펀더멘털')
 await page.getByRole('tab',{name:'Thesis',exact:true}).click()
 await expect(detail.locator('.folio-editorial-heading h3')).toContainText('내 분석')
 await expect(detail.locator('.analysis-sheet')).toBeVisible()
})

for(const width of [390,834,1440])test('Thesis writer validates numeric drafts at '+width+'px',async({page})=>{
 await page.setViewportSize({width,height:1000})
 await page.addInitScript(()=>{sessionStorage.setItem('peppercorn-intro-seen','1');localStorage.setItem('peppercorn-analysis','[]')})
 await page.route('**/data/leaderboard.json*',r=>r.fulfill({status:404,body:''}))
 await page.route('**/functions/v1/leaderboard?*',r=>r.fulfill({json:{rows:demoRows}}))
 await page.goto('/peppercorn/')
 const bottom=page.locator('.mobile-bottom-nav').getByRole('button',{name:'발견',exact:true})
 if(await bottom.isVisible())await bottom.click();else await page.locator('.sidebar nav').getByRole('button',{name:'발견',exact:true}).click()
 await page.getByRole('tab',{name:'종목 검토',exact:true}).click()
 await page.locator('.analysis-finder .stock-compact-row, .analysis-finder .stock-trend-row').first().click()
 await page.getByRole('tab',{name:'Thesis',exact:true}).click()
 const sheet=page.locator('.analysis-body .analysis-sheet')
 if(await sheet.getByRole('button',{name:'분석 기록 만들기'}).isVisible())await sheet.getByRole('button',{name:'분석 기록 만들기'}).click()
 const eps=sheet.getByLabel('분기 EPS 성장률 (YoY)')
 await expect(eps).toBeVisible()
 await eps.fill('30');await eps.blur()
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('peppercorn-analysis')||'[]')[0]?.eps_growth_q)).toBe(.3)
 await eps.fill('invalid-number');await eps.blur()
 await expect(sheet.getByRole('alert')).toHaveText('유효한 숫자를 입력해 주세요.')
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('peppercorn-analysis')||'[]')[0]?.eps_growth_q)).toBe(.3)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})
