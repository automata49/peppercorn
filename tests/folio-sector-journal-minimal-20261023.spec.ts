import {test,expect} from '@playwright/test'
import {blankSnapshot,type JournalEntry} from '../src/lib/lifetimeJournal'
import {openPage} from './journey-helpers'

test('Journal and Journey: minimal toolbar and durable confirmed deletion',async({page})=>{
 await page.setViewportSize({width:390,height:844})
 await page.addInitScript(()=>sessionStorage.setItem('peppercorn-intro-seen','1'))
 await page.route('**/functions/v1/leaderboard?*',r=>r.fulfill({json:{rows:[]}}))
 await page.route('**/functions/v1/position-public?*',r=>r.fulfill({json:{rows:[]}}))
 await page.goto('/peppercorn/')
 const entry:JournalEntry={...blankSnapshot(),id:'delete-test-01',kind:'investment',title:'삭제 테스트 투자 기록',text:'개인 작성 메모',createdAt:'2026-10-20T09:00:00Z',updatedAt:'2026-10-20T09:00:00Z',revisions:[]}
 await page.evaluate(entry=>new Promise<void>((resolve,reject)=>{
  const open=indexedDB.open('folio-lifetime-journal',1)
  open.onsuccess=()=>{
   const db=open.result,t=db.transaction('notebooks','readwrite')
   t.objectStore('notebooks').put([entry],'guest')
   t.oncomplete=()=>{db.close();resolve()}
   t.onerror=()=>reject(t.error)
  };open.onerror=()=>reject(open.error)
 }),entry)
 await page.reload()
 await openPage(page,'저널')
 await expect(page.getByRole('tab')).toContainText(['전체','일상','투자'])
 await expect(page.getByRole('searchbox',{name:'기록 찾기'})).toBeVisible()
 await expect(page.getByRole('button',{name:'날짜 · 모아보기'})).toBeVisible()
 await expect(page.locator('.journal-view-toggle button')).toHaveCount(2)
 await expect(page.getByRole('heading',{name:'나의 페이지 1개'})).toBeVisible()
 const card=page.getByRole('button',{name:'삭제 테스트 투자 기록 기록 열기'})
 await card.click()
 await expect(page.getByRole('button',{name:'기록 삭제'})).toBeVisible()
 page.once('dialog',dialog=>dialog.dismiss())
 await page.getByRole('button',{name:'기록 삭제'}).click()
 await expect(page.locator('.journal-page-reader')).toBeVisible()
 page.once('dialog',dialog=>dialog.accept())
 await page.getByRole('button',{name:'기록 삭제'}).click()
 await expect(page.getByRole('heading',{name:'나의 페이지 0개'})).toBeVisible()
 await page.reload()
 await openPage(page,'저널')
 await expect(page.getByRole('heading',{name:'나의 페이지 0개'})).toBeVisible()
 await openPage(page,'여정')
 await expect(page.locator('.decision-queue-item')).toHaveCount(0)
 const persisted=await page.evaluate(()=>new Promise<any[]>((resolve,reject)=>{
  const open=indexedDB.open('folio-lifetime-journal',1)
  open.onsuccess=()=>{const db=open.result,t=db.transaction('notebooks'),r=t.objectStore('notebooks').get('guest');r.onsuccess=()=>{db.close();resolve(r.result||[])};r.onerror=()=>reject(r.error)};open.onerror=()=>reject(open.error)
 }))
 expect(persisted).toHaveLength(1)
 expect(persisted[0].deletedAt).toBeTruthy()
 expect(persisted[0].photos).toEqual([])
 expect(persisted[0].text).toBe('')
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1)).toBe(true)
})

