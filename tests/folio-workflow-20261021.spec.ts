import {test,expect} from '@playwright/test'
import {demoRows} from '../src/data/mock'

test('Discover defaults to Market Signal, opens canonical stocks and restores tabs on Back',async({page})=>{
 await page.addInitScript(()=>{sessionStorage.setItem('peppercorn-intro-seen','1');localStorage.setItem('folio-stock-size','all')})
 await page.route('**/functions/v1/leaderboard?*',route=>route.fulfill({json:{rows:demoRows}}))
 await page.route('**/data/leaderboard.json*',route=>route.fulfill({status:404,body:''}))
 await page.goto('/peppercorn/')
 await page.locator('.sidebar nav').getByRole('button',{name:'발견',exact:true}).click()
 await expect(page.getByRole('tablist',{name:'발견 영역'}).getByRole('tab',{name:'시장 신호'})).toHaveAttribute('data-state','active')
 await expect(page.locator('.leader-tools-trigger,.signal-journey-heading')).toHaveCount(0)
 await page.getByRole('tab',{name:'종목 검토',exact:true}).click()
 await expect(page.getByRole('tablist',{name:'발견 영역'}).getByRole('tab',{name:'종목 검토'})).toHaveAttribute('data-state','active')
 const wheel=page.locator('.analysis-finder [data-wheel="주도 분류"]')
 await expect(wheel.locator('button')).toHaveText(['핵심 주도','주도 후보','강세 전환','조정 중','전체'])
 await expect(wheel.locator('.catalog-wheel-selection')).toBeVisible()
 await page.evaluate(()=>history.back())
 await expect(page.getByRole('tablist',{name:'발견 영역'}).getByRole('tab',{name:'시장 신호'})).toHaveAttribute('data-state','active')
})
test('Journey menu shares existing watchlist and portfolio records; research compares by field',async({page})=>{
 await page.addInitScript(()=>sessionStorage.setItem('peppercorn-intro-seen','1'))
 await page.goto('/peppercorn/')
 await page.locator('.sidebar-tools').click()
 await page.getByRole('dialog').getByRole('button',{name:'관심 종목 · Watchlist'}).click()
 await expect(page.locator('.journey-magazine-tabs').getByRole('tab',{name:'관심종목'})).toHaveAttribute('data-state','active')
 await page.locator('.sidebar-tools').click()
 await page.getByRole('dialog').getByRole('button',{name:'보유 종목 · Portfolio'}).click()
 await expect(page.locator('.journey-magazine-tabs').getByRole('tab',{name:'보유종목'})).toHaveAttribute('data-state','active')
 await page.locator('.sidebar-tools').click()
 await page.getByRole('dialog').getByRole('button',{name:'리서치 노트'}).click()
 const table=page.locator('.vertical-compare-table')
 await expect(table).toBeVisible()
 await expect(table.locator('thead th').first()).toHaveText('항목')
 await expect(table.locator('tbody th').first()).toHaveText('작성일')
})
